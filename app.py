def _parse_gemini_json(text: str) -> dict:
    text = text.strip()
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass

    # Try ```json ... ``` blocks.
    fenced = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", text, flags=re.IGNORECASE)
    if fenced:
        return json.loads(fenced.group(1))

    # Fallback: slice to the first/last JSON object.
    start = text.find("{")
    end = text.rfind("}")
    if start != -1 and end != -1 and end > start:
        return json.loads(text[start : end + 1])

    raise ValueError("Could not parse model output as JSON.")


def _is_valid_email(value: str) -> bool:
    value = value.strip()
    if not value:
        return False
    # Accept all standard email formats including .ac.in, .co.in etc
    return re.match(r"^[^@\s]+@[^@\s]+\.[^@\s.]+(\.[^@\s.]+)*$", value) is not None


def _build_email_body(person_responsible: str, action_item: str, deadline: str, priority: str = "Low") -> str:
    import urllib.parse
    from datetime import datetime, timedelta
    import re

    person = person_responsible.strip() or "there"
    deadline_text = deadline.strip() or "Not specified"
    action_text = action_item.strip() or "Not specified"

    # Build Google Calendar link
    title = urllib.parse.quote(action_text)
    details = urllib.parse.quote(
        f"Assigned to: {person}\nDeadline: {deadline_text}\nPriority: {priority}\nGenerated by MeetingMind"
    )

    # Try to parse date from deadline text (expecting YYYY-MM-DD from AI)
    start_date = None
    if deadline:
        m = re.search(r"(\d{4}-\d{2}-\d{2})", deadline)
        if m:
            try:
                start_date = datetime.strptime(m.group(1), "%Y-%m-%d")
            except ValueError:
                pass

    if not start_date:
        start_date = datetime.now() + timedelta(days=7)

    end_date = start_date + timedelta(days=1)
    fmt_date = lambda d: d.strftime("%Y%m%d")
    dates = f"{fmt_date(start_date)}/{fmt_date(end_date)}"

    calendar_link = (
        f"https://calendar.google.com/calendar/render?action=TEMPLATE"
        f"&text={title}&details={details}&dates={dates}"
    )

    return f"""Hi {person},

You have been assigned an action item from a recent meeting:

Action Item : {action_text}
Deadline    : {deadline_text}
Priority    : {priority}

Add this directly to your Google Calendar with one click:
{calendar_link}

Please let me know if you have any questions.

Best regards,
MeetingMind
"""


def send_action_item_emails(action_items: list[dict], emails: list[str]) -> tuple[int, int]:
    api_key = os.getenv("BREVO_API_KEY", "").strip()
    sender_email = os.getenv("SENDER_EMAIL", "").strip()

    if not api_key:
        raise RuntimeError("BREVO_API_KEY is missing from environment.")

    to_pairs = []
    for idx, item in enumerate(action_items):
        email = (emails[idx] if idx < len(emails) else "").strip()
        if email and _is_valid_email(email):
            to_pairs.append((email, item))

    sent_count = 0
    skipped_count = len(action_items) - len(to_pairs)

    if not to_pairs:
        return 0, skipped_count

    subject = "Action item assigned to you — MeetingMind"
    url = "https://api.brevo.com/v3/smtp/email"
    headers = {"api-key": api_key, "Content-Type": "application/json"}

    for to_email, item in to_pairs:
        body = _build_email_body(
            person_responsible=str(item.get("person_responsible", "")),
            action_item=str(item.get("action_item", "")),
            deadline=str(item.get("deadline", "")),
            priority=str(item.get("priority", "Medium")),
        )
        payload = {
            "sender": {"name": "MeetingMind", "email": sender_email},
            "to": [{"email": to_email}],
            "subject": subject,
            "textContent": body,
        }
        try:
            response = requests.post(url, headers=headers, json=payload, timeout=30)
            if response.status_code == 201:
                sent_count += 1
        except Exception:
            pass

    return sent_count, skipped_count


def extract_action_items(transcript: str) -> list[dict]:
    from datetime import datetime
    
    api_key = os.getenv("GROQ_API_KEY")
    if not api_key:
        raise RuntimeError("GROQ_API_KEY is missing. Please set it in the root .env file.")

    today_date = datetime.now().strftime("%Y-%m-%d")
    today_weekday = datetime.now().strftime("%A")
    
    system_prompt = f"""
You extract structured action items from meeting transcripts.

The transcript uses "Speaker A:", "Speaker B:" labels to identify who is speaking.
When someone says "I will", "I'll", "I can", "my task" — the assignee is the Speaker label for that line.
Extract the speaker label as the assignee name (e.g. "Speaker A").
Do NOT hallucinate or guess real names — only use what's in the transcript.

Extract action items (specific next steps). For each action item, include:
- person_responsible: who is responsible (use the Speaker label like "Speaker A" or "Speaker B")
- deadline: the due date as YYYY-MM-DD format (e.g. "2026-04-09"). 
  If the transcript says "Wednesday", "next Friday", "in 3 days", or similar relative dates, 
  convert it to the actual date based on today. 
  Today's date is {today_date} ({today_weekday}).
  If no date is stated, use empty string "".
- priority: urgency level (High or Low) based on:
  * High = urgent, time-sensitive, or critical for business
  * Low = important but not immediately urgent, or nice to have

Return ONLY valid JSON (no markdown, no commentary) with the exact schema:
{{
  "action_items": [
    {{
      "action_item": "...",
      "person_responsible": "...",
      "deadline": "...",
      "priority": "High|Low"
    }}
  ]
}}

Rules:
- Use empty string "" when a field is not explicitly stated.
- For priority, analyze urgency and importance from context.
- Always convert relative dates to YYYY-MM-DD format based on today's date.
- If there are no action items, return {{"action_items": []}}.
- When the transcript has Speaker A, Speaker B labels, use those labels as person_responsible values.
""".strip()

    user_prompt = f"Transcript:\n{transcript}".strip()

    url = "https://api.groq.com/openai/v1/chat/completions"
    payload = {
        "model": "llama-3.3-70b-versatile",
        "messages": [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ],
        "temperature": 0.2,
        "max_tokens": 512,
    }

    headers = {"Authorization": f"Bearer {api_key}"}
    resp = requests.post(url, headers=headers, json=payload, timeout=60)
    if not resp.ok:
        raise RuntimeError(f"Groq API error {resp.status_code}: {resp.text}")

    data = resp.json()
    content = (
        data.get("choices", [{}])[0]
        .get("message", {})
        .get("content", "")
    )
    if not content:
        raise ValueError("Groq returned empty content; expected JSON.")

    parsed = _parse_gemini_json(content)

    if not isinstance(parsed, dict):
        raise ValueError("AI returned invalid JSON structure.")

    items = parsed.get("action_items") or []
    if not isinstance(items, list):
        raise ValueError("AI returned invalid action_items structure.")

    normalized: list[dict] = []
    for item in items:
        if not isinstance(item, dict):
            continue
        normalized.append(
            {
                "action_item": str(item.get("action_item", "") or ""),
                "person_responsible": str(item.get("person_responsible", "") or ""),
                "deadline": str(item.get("deadline", "") or ""),
                "priority": str(item.get("priority", "Low") or "Low"),
            }
        )
    return normalized


