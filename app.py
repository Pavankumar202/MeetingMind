@app.post("/export_calendar")
def export_calendar():
    import re
    from datetime import datetime, timedelta

    action_items = session.get("action_items", [])
    if not isinstance(action_items, list):
        action_items = []

    if not action_items:
        data = request.get_json(silent=True) or {}
        action_items = data.get("action_items", [])

    now = datetime.now()
    now_utc = datetime.now(timezone.utc)
    now_stamp = now_utc.strftime("%Y%m%dT%H%M%SZ")

    cal_lines = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//MeetingMind//MeetingMind 1.0//EN",
        "CALSCALE:GREGORIAN",
        "METHOD:PUBLISH",
        "X-MS-OLK-FORCEINSPECTOROPEN:TRUE",
        "X-WR-CALNAME:MeetingMind Action Items",
    ]

    def ics_escape(text: str) -> str:
        text = str(text).strip()
        text = text.replace("\\", "\\\\")
        text = text.replace(";", "\\;")
        text = text.replace(",", "\\,")
        text = text.replace("\r\n", "\\n")
        text = text.replace("\n", "\\n")
        text = text.replace("\r", "\\n")
        return text

    def fold_line(line: str) -> str:
        if len(line.encode("utf-8")) <= 75:
            return line
        result = []
        while len(line.encode("utf-8")) > 75:
            chunk = line[:75]
            while len(chunk.encode("utf-8")) > 75:
                chunk = chunk[:-1]
            result.append(chunk)
            line = " " + line[len(chunk):]
        result.append(line)
        return "\r\n".join(result)

    def parse_date(deadline_raw: str):
        if not deadline_raw:
            return None
        m = re.search(r"(\d{4}-\d{2}-\d{2})", deadline_raw)
        if m:
            try:
                return datetime.strptime(m.group(1), "%Y-%m-%d")
            except ValueError:
                return None
        return None

    for idx, item in enumerate(action_items):
        if not isinstance(item, dict):
            continue

        action      = item.get("action_item", "Action Item") or "Action Item"
        person      = item.get("person_responsible", "") or ""
        deadline_raw = item.get("deadline", "") or ""
        priority_str = item.get("priority", "Low") or "Low"

        event_date = parse_date(deadline_raw) or (now + timedelta(days=7))
        date_str   = event_date.strftime("%Y%m%d")
        end_date_str = (event_date + timedelta(days=1)).strftime("%Y%m%d")

        outlook_priority = {"High": "1", "Low": "9"}.get(priority_str, "9")

        desc_parts = []
        if person:
            desc_parts.append(f"Assigned to: {person}")
        desc_parts.append(f"Deadline: {deadline_raw if deadline_raw else 'Not specified'}")
        desc_parts.append(f"Priority: {priority_str}")
        desc_parts.append("Generated by MeetingMind")
        description = ics_escape("\\n".join(desc_parts))

        uid = f"meetingmind-{now_stamp}-{idx}@meetingmind.local"

        event_lines = [
            "BEGIN:VEVENT",
            f"UID:{uid}",
            f"DTSTAMP:{now_stamp}",
            f"DTSTART;VALUE=DATE:{date_str}",
            f"DTEND;VALUE=DATE:{end_date_str}",
            f"SUMMARY:{ics_escape(action)}",
            f"DESCRIPTION:{description}",
            f"PRIORITY:{outlook_priority}",
            f"X-MS-OLK-SENDER:{person if person else 'MeetingMind'}",
            "TRANSP:TRANSPARENT",
            "STATUS:CONFIRMED",
            "CLASS:PUBLIC",
            "END:VEVENT",
        ]
        cal_lines.extend(event_lines)

    cal_lines.append("END:VCALENDAR")

    folded = [fold_line(line) for line in cal_lines]
    ics_content = "\r\n".join(folded) + "\r\n"

    return send_file(
        io.BytesIO(ics_content.encode("utf-8")),
        as_attachment=True,
        download_name="meetingmind_actions.ics",
        mimetype="text/calendar; charset=utf-8",
    )


